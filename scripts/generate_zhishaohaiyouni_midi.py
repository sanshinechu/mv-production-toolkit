def create_authentic_midi(output_path: Path):
    midi = pretty_midi.PrettyMIDI(initial_tempo=BPM)
    instrument = pretty_midi.Instrument(program=0, name="Vocal Melody - Zhi Shao Hai You Ni")

    current_beat = 4.0  # 1 小節前奏休止
    for lyric, pitch_str, dur, rest in REAL_SONG_PHRASES:
        pitch = PITCH_MAP_E[pitch_str]
        start_time = current_beat * BEAT_SEC
        end_time = (current_beat + dur * 0.92) * BEAT_SEC
        note = pretty_midi.Note(velocity=100, pitch=pitch, start=start_time, end=end_time)
        instrument.notes.append(note)
        current_beat += dur + rest

    midi.instruments.append(instrument)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    midi.write(str(output_path))
    print(f"Generated {output_path} with {len(instrument.notes)} notes, duration: {midi.get_end_time():.2f}s")


